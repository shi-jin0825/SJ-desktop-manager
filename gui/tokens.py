# -*- coding: utf-8 -*-
"""设计令牌：间距 / 字号 / 常用控件尺寸。

早先这些值散在各页面里随手写：间距 177 处用了 18 个不同的值（3px 出现 14 次，
5/11/13 是体系外的孤值），字号 93 处用了 13 个值（还有 font(7) 这种低于可读
下限的），连进度条高度都同时存在 8px 和 10px 两套。想统一一个视觉规范，等于
满仓库找数字。这里收敛成两把标尺：页面只写「语义」（这是区块间距还是控件
间距），具体像素由这里决定。

高 DPI：程序声明了 Per-Monitor DPI 感知，Tk 会把「点数」字号按缩放自动放大
（11pt 在 150% 屏上约 22px），但布局常量是像素、不会自动跟——字大容器小，
什么都被挤爆。所以这里的所有尺寸常量统一乘 UI_SCALE（px()），字号仍写
「标准 96dpi 下的点数」，两边一起缩，观感在任何缩放下都一致。
"""
from core.dpi import scale_factor

UI_SCALE = max(1.0, min(2.0, scale_factor()))


def px(v: int) -> int:
    """逻辑像素 → 当前缩放下的物理像素。"""
    return int(round(v * UI_SCALE))


# ---- 间距：4 档基础 + 2 档大留白 ----
SPACING = {
    "none": 0,     # 贴边
    "xs": px(4),       # 控件内部、图标与文字之间（原 2/3/4/5 混用）
    "sm": px(8),       # 相邻控件（原 6/7/8）
    "md": px(12),      # 区块内部（原 10/11/12/13）
    "lg": px(16),      # 页面边距、区块之间（原 14/16/18）
    "xl": px(24),      # 大区块之间（原 20/24）
    "xxl": px(40),     # 空态留白（原 40/60）
}
SP = SPACING      # 简写：padx=SP["md"]

# ---- 字号：7 档，最小 10（再小在正常 DPI 上已经读不清）----
# 注意：这里存的是「标准缩放下的点数」，font() 交给 Tk 后会随系统 DPI
# 自动放大，不要再乘 UI_SCALE。
TYPE = {
    "xs": 10,      # 脚注 / 卡片次要信息（原 7/8/9）
    "sm": 11,      # 正文（原 10/11）
    "md": 12,      # 小标题（原 12/13）
    "lg": 14,      # 区块标题（原 14）
    "title": 17,   # 页面主标题（顶栏那个，比区块标题再大一档）
    "xl": 20,      # 大数字（原 20/22）
    "hero": 28,    # 头部大数字 / 标题（原 28/30/34）
}
FS = TYPE         # 简写：font(FS["xs"])

# ---- 常用尺寸 ----
BAR_H = px(10)    # 进度条高度（原来统计/监控 10px、倒计时 8px 两套）
TOPBAR_H = px(64)  # 顶栏高度

# ---- 侧边栏 ----
# 宽度收在这里：以前 208 / 210 / 240 来回改，页面里还散着和宽度配套的
# 缩进，改一处就崩一处。现在「栏宽 + 行高 + 图标 + 缩进」一套取值。
SIDEBAR_W = px(240)       # 展开宽度（240 是主流桌面应用的舒适宽度，长文字也放得下）
SIDEBAR_W_MINI = px(72)   # 折叠后宽度（只留图标，72 让图标不贴边）
TEXT_PAD = px(8)          # 文字右侧保底留白（避免长文字顶到栏边缘被裁）

# 侧边栏：导航项比底部项高一档、图标大一档，保持层级差
NAV_H = px(44)        # 导航项行高（36 是主流侧栏的下限，抬到 44 才不显局促）
NAV_H_MIN = px(26)    # 窗口很矮时导航项能压到的下限（保住 6 项 + 底部键都可见）
NAV_ICON = px(22)     # 导航项图标
NAV_H_SM = px(38)     # 底部项行高（和搜索框同档）
NAV_ICON_SM = px(19)  # 底部项图标（比导航图标小一档）
NAV_PAD = (px(13), px(11))  # 侧边栏图标的左缩进 / 与文字间距（栏宽 240 时配套）
AVATAR = px(32)       # 侧边栏头像（按设计稿：小头像 + 用户名两行信息的紧凑样式）

BTN_H = px(38)        # 侧边栏搜索框 / 底部项（胶囊控件）
BTN_H_LG = px(40)     # 页面工具栏 / 弹窗按钮（比侧栏控件再大一档）
BTN_H_SM = px(34)     # 卡片内的小按钮
BTN_PAD = px(20)      # 胶囊按钮的横向内边距（加大按钮后跟着放宽）
